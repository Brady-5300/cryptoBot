import base64

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ed25519, padding, rsa

from basis.venues.kalshi.auth import KalshiSigner, load_private_key
from basis.venues.robinhood.auth import RobinhoodSigner


def _pem(key: rsa.RSAPrivateKey | ed25519.Ed25519PrivateKey) -> bytes:
    return key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )


def test_kalshi_rsa_pss_signature_verifies_and_strips_query() -> None:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    signer = KalshiSigner("kid", load_private_key(_pem(key)))
    h = signer.headers("get", "/trade-api/v2/margin/balance?x=1", 1703123456789)
    assert h["KALSHI-ACCESS-KEY"] == "kid"
    assert h["KALSHI-ACCESS-TIMESTAMP"] == "1703123456789"
    key.public_key().verify(
        base64.b64decode(h["KALSHI-ACCESS-SIGNATURE"]),
        b"1703123456789GET/trade-api/v2/margin/balance",
        padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=padding.PSS.DIGEST_LENGTH),
        hashes.SHA256(),
    )


def test_kalshi_ed25519_signature_verifies() -> None:
    key = ed25519.Ed25519PrivateKey.generate()
    signer = KalshiSigner("kid", load_private_key(_pem(key)))
    h = signer.headers("GET", "/trade-api/ws/v2/margin", 1)
    key.public_key().verify(
        base64.b64decode(h["KALSHI-ACCESS-SIGNATURE"]), b"1GET/trade-api/ws/v2/margin"
    )


def test_robinhood_official_test_vector() -> None:
    """Example values published at docs.robinhood.com/crypto/trading (Example Signature).
    These are Robinhood's public documentation keys, not real credentials."""
    signer = RobinhoodSigner(
        "rh-api-6148effc-c0b1-486c-8940-a1d099456be6",
        "xQnTJVeQLmw1/Mg2YimEViSpw/SdJcgNXZ5kQkAXNPU=",
    )
    # The published signature was generated by the docs' Python sample, which interpolates
    # the body *dict* (str(body), single quotes), not JSON. Reproducing it with that exact
    # string verifies our message layout; real requests sign the exact JSON bytes sent.
    body = str(
        {
            "client_order_id": "131de903-5a9c-4260-abc1-28d562a5dcf0",
            "side": "buy",
            "symbol": "BTC-USD",
            "type": "market",
            "market_order_config": {"asset_quantity": "0.1"},
        }
    )
    expected = (
        "q/nEtxp/P2Or3hph3KejBqnw5o9qeuQ+hYRnB56FaHbjDsNUY9KhB1asMxohDnzdVFSD7StaTqjSd9U9HvaRAw=="
    )
    assert signer.signature(1698708981, "/api/v1/crypto/trading/orders/", "POST", body) == expected
    pub = base64.b64decode("jPItx4TLjcnSUnmnXQQyAKL4eJj3+oWNNMmmm2vATqk=")
    assert signer._key.public_key().public_bytes_raw() == pub
    assert "xQnTJ" not in repr(signer)
